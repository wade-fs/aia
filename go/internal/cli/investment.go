var invPredictionsCmd = &cobra.Command{
	Use:   "predictions",
	Short: "List recorded forecasts and verification status",
	RunE: func(cmd *cobra.Command, args []string) error {
		ctx := context.Background()
		preds, err := appInst.InvSvc.ListPredictions(ctx, "", 50)
		if err != nil {
			return err
		}

		if len(preds) == 0 {
			fmt.Println("No investment predictions recorded.")
			return nil
		}

		w := tabwriter.NewWriter(os.Stdout, 0, 0, 3, ' ', 0)
		fmt.Fprintln(w, "ID\tTYPE\tDIRECTION\tPROB\tHORIZON\tSTATUS\tDUE AT")
		for _, p := range preds {
			idShort := p.ID
			if len(idShort) > 8 {
				idShort = idShort[:8]
			}
			fmt.Fprintf(w, "%s\t%s\t%s\t%.1f%%\t%s\t%s\t%s\n",
				idShort, p.PredictionType, p.ExpectedDirection, p.Probability*100, p.EvaluationHorizon, p.Status, p.DueAt.Format("2006-01-02 15:04"))
		}
		w.Flush()
		return nil
	},
}

var invEvaluateCmd = &cobra.Command{
	Use:   "evaluate",
	Short: "Evaluate due predictions against market outcomes and compute calibration score",
	RunE: func(cmd *cobra.Command, args []string) error {
		ctx := context.Background()
		fmt.Println("Running prediction evaluation against actual market data...")
		outcomes, evalResult, err := appInst.InvSvc.EvaluatePredictions(ctx)
		if err != nil {
			return err
		}

		fmt.Printf("✓ Evaluated %d due prediction(s)\n", len(outcomes))
		for _, oc := range outcomes {
			fmt.Printf("  - Prediction %s: Status=%s, Direction=%s (Actual: %.2f%%), Brier Score=%.4f\n",
				oc.PredictionID[:8], oc.OutcomeStatus, oc.ActualDirection, oc.ActualValue, oc.BrierScore)
		}

		if evalResult != nil {
			fmt.Println("\n=== Overall Calibration Performance ===")
			fmt.Printf("Sample Count: %d\n", evalResult.SampleCount)
			fmt.Printf("Metrics: %s\n", evalResult.MetricsJSON)
		}
		return nil
	},
}

var (
	cashReason string
)

var invSetCapitalCmd = &cobra.Command{
	Use:   "set-capital <amount>",
	Short: "Update investment capital limit in NT$ (e.g. 1500000)",
	Args:  cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		ctx := context.Background()
		amount, err := strconv.ParseInt(args[0], 10, 64)
		if err != nil || amount < 0 {
			return fmt.Errorf("invalid capital limit amount: %s", args[0])
		}
		if err := appInst.InvSvc.SetCapitalLimit(ctx, amount); err != nil {
			return err
		}
		fmt.Printf("✓ Successfully updated Capital Limit to NT$ %s\n", formatMoney(amount))
		return nil
	},
}

var invSetCashCmd = &cobra.Command{
	Use:   "set-cash <amount>",
	Short: "Update available cash in NT$ (e.g. 800000)",
	Args:  cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		ctx := context.Background()
		amount, err := strconv.ParseInt(args[0], 10, 64)
		if err != nil || amount < 0 {
			return fmt.Errorf("invalid cash amount: %s", args[0])
		}
		snap, err := appInst.InvSvc.SetAvailableCash(ctx, amount, cashReason)
		if err != nil {
			return err
		}
		fmt.Printf("✓ Successfully updated Available Cash to NT$ %s (Total Portfolio Value: NT$ %s)\n",
			formatMoney(snap.AvailableCash), formatMoney(snap.TotalPortfolioValue))
		return nil
	},
}

func init() {
	invSetCashCmd.Flags().StringVarP(&cashReason, "reason", "r", "Manual cash adjustment via CLI", "Reason for cash change")

	investmentCmd.AddCommand(invPortfolioCmd)
	investmentCmd.AddCommand(invSetCapitalCmd)
	investmentCmd.AddCommand(invSetCashCmd)
	investmentCmd.AddCommand(invSyncCmd)
	investmentCmd.AddCommand(invProposalsCmd)
	investmentCmd.AddCommand(invApproveCmd)
	investmentCmd.AddCommand(invRejectCmd)
	investmentCmd.AddCommand(invPredictionsCmd)
	investmentCmd.AddCommand(invEvaluateCmd)
}

func formatMoney(n int64) string {
	in := strconv.FormatInt(n, 10)
	var out []string
	for len(in) > 3 {
		out = append([]string{in[len(in)-3:]}, out...)
		in = in[:len(in)-3]
	}
	if len(in) > 0 {
		out = append([]string{in}, out...)
	}
	return strings.Join(out, ",")
}
