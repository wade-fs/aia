var investmentCmd = &cobra.Command{
	Use:   "investment",
	Short: "Manage investment portfolio, sync data, view predictions and proposals",
	Long: `The investment command suite interacts with the AIA Investment Agent core.
All financial calculations, sizing, and risk constraints are strictly enforced by Go.`,
}

var invPortfolioCmd = &cobra.Command{
	Use:   "portfolio",
	Short: "Show current portfolio profile, cash, constraints, and positions",
	RunE: func(cmd *cobra.Command, args []string) error {
		ctx := context.Background()
		prof, err := appInst.InvSvc.GetProfile(ctx)
		if err != nil {
			return err
		}

		snap, positions, err := appInst.InvSvc.GetSnapshot(ctx)
		if err != nil {
			return err
		}

		fmt.Println("=== Investment Portfolio Profile ===")
		fmt.Printf("Profile: %s (%s)\n", prof.Name, prof.Market)
		fmt.Printf("Capital Limit: NT$ %s (%s)\n", formatMoney(prof.CapitalLimit), prof.CapitalLimitBasis)
		fmt.Printf("Available Cash: NT$ %s\n", formatMoney(snap.AvailableCash))
		fmt.Printf("Total Value: NT$ %s\n", formatMoney(snap.TotalPortfolioValue))
		fmt.Printf("Auto-Trading: %v (Disabled by architecture)\n\n", prof.AutoTradingEnabled)

		fmt.Println("=== Current Positions ===")
		if len(positions) == 0 {
			fmt.Println("No positions currently held.")
		} else {
			w := tabwriter.NewWriter(os.Stdout, 0, 0, 3, ' ', 0)
			fmt.Fprintln(w, "INSTRUMENT\tQUANTITY\tAVG COST\tLAST PRICE\tMARKET VALUE")
			for _, pos := range positions {
				fmt.Fprintf(w, "%s\t%d\t%.2f\t%.2f\tNT$ %s\n",
					pos.InstrumentID, pos.Quantity, pos.AverageCost, pos.LastKnownPrice, formatMoney(pos.MarketValue))
			}
			w.Flush()
		}
		return nil
	},
}

var invSyncCmd = &cobra.Command{
	Use:   "sync [symbol]",
	Short: "Fetch latest market price bars and announcements for a stock (e.g. 2330)",
	Args:  cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		ctx := context.Background()
		symbol := args[0]
		fmt.Printf("Syncing market data and official announcements for %s...\n", symbol)

		md, err := appInst.InvSvc.SyncMarketData(ctx, symbol)
		if err != nil {
			return fmt.Errorf("sync market data error: %w", err)
		}

		docs, err := appInst.InvSvc.SyncAnnouncements(ctx, symbol)
		if err != nil {
			return fmt.Errorf("sync announcements error: %w", err)
		}

		fmt.Printf("✓ Successfully synced market bar (effective at: %s)\n", md.EffectiveAt.Format("2006-01-02 15:04:05"))
		fmt.Printf("✓ Ingested %d official documents/news:\n", len(docs))
		for _, d := range docs {
			fmt.Printf("  - [%s] %s (%s)\n", d.ContentType, d.Title, d.PublishedAt.Format("2006-01-02"))
		}
		return nil
	},
}

var invProposalsCmd = &cobra.Command{
	Use:   "proposals",
	Short: "List trade proposals generated by Go Runtime",
	RunE: func(cmd *cobra.Command, args []string) error {
		ctx := context.Background()
		proposals, err := appInst.InvSvc.ListProposals(ctx, "", 50)
		if err != nil {
			return err
		}

		if len(proposals) == 0 {
			fmt.Println("No trade proposals found.")
			return nil
		}

		w := tabwriter.NewWriter(os.Stdout, 0, 0, 3, ' ', 0)
		fmt.Fprintln(w, "ID\tACTION\tSHARES\tEST PRICE\tTOTAL COST\tSTATUS\tREASON")
		for _, p := range proposals {
			idShort := p.ID
			if len(idShort) > 8 {
				idShort = idShort[:8]
			}
			fmt.Fprintf(w, "%s\t%s\t%d\t%.2f\tNT$ %s\t%s\t%s\n",
				idShort, p.Action, p.Quantity, p.EstimatedPrice, formatMoney(p.EstimatedTotalCost), p.Status, p.StatusReason)
		}
		w.Flush()
		return nil
	},
}

